static void print_buffer_comparison(uint8_t *wanted_result, uint8_t *result, size_t length)
{
	int i, j;

	printk("Was waiting for: \n");

	for (i = 0, j = 1; i < length; i++, j++) {
		printk("0x%02x ", wanted_result[i]);

		if (j == 10) {
			printk("\n");
			j = 0;
		}
	}

	printk("\n But got:\n");

	for (i = 0, j = 1; i < length; i++, j++) {
		printk("0x%02x ", result[i]);

		if (j == 10) {
			printk("\n");
			j = 0;
		}
	}

	printk("\n");
}
static void *Hash256_LightPadding(char *m, uint64_t len, uint64_t *nopadding_len,
				  uint8_t *padding_len)
{
	printk("len = %lld \n",len);
	if (len % 64) {
		*padding_len = 64;

		if ((len * 8 + 1) % 512 > 448) {
			*padding_len += 64;
			printk("111\n");
		}

		*nopadding_len = (len / 64) * 64; // Floor
		printk("123\n");
	} else {
		*nopadding_len = len;
		*padding_len = 64;
		printk("321\n");
	}

	unsigned char *s = (unsigned char *)k_malloc(*padding_len);

	memset(s, 0, *padding_len);

	uint8_t i;

	for (i = 0; i < len - *nopadding_len; i++) {
		s[i] = m[*nopadding_len + i];
	}

	s[i] = 0x80;

	for (i = 0; i < 8; i++) {
		s[*padding_len - 1 - i] =
			(unsigned char)(((uint64_t)(len * 8) & (uint64_t)(0xff << i * 8)) >> 8 * i);
	}

	return s;
}

